import type {
  DurableObjectNamespace,
  ExecutionContext,
  MessageBatch,
  Queue,
  ScheduledController,
} from "@cloudflare/workers-types";
import { serveAssetWithRange, type AssetsFetcher } from "./range";
import { RelayNestState } from "./state-do";

// Custom Cloudflare Worker entrypoint wrapping OpenNext's generated handler so:
// 1. Cloudflare Cron Triggers (`* * * * *`) invoke RelayNest's `/api/cron/tick` route.
// 2. Cloudflare Queues (`relaynest-events`) invoke `/api/queues/cloudflare` with per-message ack/retry backoff.
// 3. `RelayNestState` (SQLite Durable Object) powers edge rate limiting, cache/dedupe, and Telegram send pacing.
// 4. `/video/*` static assets honor HTTP `Range` (`206 Partial Content`) requests for video seeking.
// @ts-expect-error: generated by `pnpm build:cloudflare` into `frontend/.open-next/worker.js`
import openNextHandler from "../frontend/.open-next/worker.js";

// Re-export OpenNext Durable Objects and RelayNest's free-tier SQLite state Durable Object.
// @ts-expect-error: generated by `pnpm build:cloudflare` into `frontend/.open-next/worker.js`
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from "../frontend/.open-next/worker.js";
export { RelayNestState };

interface RelayNestWorkerEnv {
  ASSETS?: AssetsFetcher;
  RELAYNEST_STATE?: DurableObjectNamespace<RelayNestState>;
  RELAYNEST_QUEUE?: Queue;
  CRON_SECRET?: string;
  KAFKA_CONSUMER_SECRET?: string;
  NEXT_PUBLIC_APP_URL?: string;
  [key: string]: unknown;
}

function resolveOrigin(env: RelayNestWorkerEnv): string {
  return typeof env.NEXT_PUBLIC_APP_URL === "string" && /^https?:\/\//.test(env.NEXT_PUBLIC_APP_URL)
    ? env.NEXT_PUBLIC_APP_URL.replace(/\/$/, "")
    : "https://relaynest.internal";
}

function resolveQueueSecret(env: RelayNestWorkerEnv): string {
  const kafkaSec = typeof env.KAFKA_CONSUMER_SECRET === "string" ? env.KAFKA_CONSUMER_SECRET.trim() : "";
  if (kafkaSec) return kafkaSec;
  return typeof env.CRON_SECRET === "string" ? env.CRON_SECRET.trim() : "";
}

const worker = {
  async fetch(request: Request, env: RelayNestWorkerEnv, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);
    if (
      url.pathname.startsWith("/video/") &&
      (request.method === "GET" || request.method === "HEAD") &&
      env.ASSETS
    ) {
      return serveAssetWithRange(request, env.ASSETS);
    }
    return openNextHandler.fetch(request, env, ctx);
  },

  async scheduled(_controller: ScheduledController, env: RelayNestWorkerEnv, ctx: ExecutionContext) {
    const cronSecret = typeof env.CRON_SECRET === "string" ? env.CRON_SECRET.trim() : "";
    if (!cronSecret) return;

    const request = new Request(`${resolveOrigin(env)}/api/cron/tick`, {
      method: "POST",
      headers: {
        Authorization: `Bearer ${cronSecret}`,
      },
    });

    ctx.waitUntil(
      Promise.resolve(openNextHandler.fetch(request, env, ctx)).then((res: Response) => {
        if (!res.ok) {
          console.error(`[cron] /api/cron/tick failed with HTTP ${res.status}`);
        }
      }),
    );
  },

  async queue(batch: MessageBatch<unknown>, env: RelayNestWorkerEnv, ctx: ExecutionContext): Promise<void> {
    const secret = resolveQueueSecret(env);
    if (!secret) {
      console.error("[queue] CRON_SECRET / KAFKA_CONSUMER_SECRET missing; retrying batch");
      batch.retryAll({ delaySeconds: 30 });
      return;
    }

    const origin = resolveOrigin(env);
    await Promise.all(
      batch.messages.map(async (msg) => {
        try {
          const req = new Request(`${origin}/api/queues/cloudflare`, {
            method: "POST",
            headers: {
              Authorization: `Bearer ${secret}`,
              "content-type": "application/json",
            },
            body: JSON.stringify({
              id: msg.id,
              attempts: msg.attempts,
              timestamp: msg.timestamp instanceof Date ? msg.timestamp.toISOString() : String(msg.timestamp),
              body: msg.body,
            }),
          });
          const res: Response = await openNextHandler.fetch(req, env, ctx);
          const parsed = (await res.json().catch(() => null)) as {
            data?: { action?: "ack" | "retry"; delaySeconds?: number };
            action?: "ack" | "retry";
            delaySeconds?: number;
          } | null;
          const outcome = parsed?.data ?? parsed;

          if (res.ok && outcome?.action !== "retry") {
            msg.ack();
            return;
          }

          const retryDelay =
            typeof outcome?.delaySeconds === "number" && Number.isFinite(outcome.delaySeconds)
              ? Math.min(Math.max(1, Math.ceil(outcome.delaySeconds)), 3600)
              : Math.min(60, 2 ** Math.min(msg.attempts, 5));
          msg.retry({ delaySeconds: retryDelay });
        } catch (err) {
          console.error("[queue] consumer dispatch error:", err instanceof Error ? err.message : "unknown");
          msg.retry({ delaySeconds: Math.min(60, 2 ** Math.min(msg.attempts, 5)) });
        }
      }),
    );
  },
};

export default worker;
