/**
 * Renders backend/src/server/ai/model-catalog.ts into an idempotent seed migration.
 * Usage: pnpm models:sql
 */
import { writeFileSync } from "node:fs";
import { MODEL_CATALOG, type CatalogModel } from "../backend/src/server/ai/model-catalog";

const OUT = "supabase/migrations/20260101000700_seed_ai_models.sql";

const str = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const num = (v: number | null) => (v === null ? "null" : String(v));
const arr = (v: string[]) => `array[${v.map((x) => str(x)).join(", ")}]::text[]`;
const bool = (v: boolean) => (v ? "true" : "false");

function row(m: CatalogModel) {
  return `  (${[
    str(m.slug), str(m.name), str(m.providerKey), str(m.providerName), str(m.source), str(m.sourceUrl), str(m.apiModelId), str(m.modelType),
    str(m.badge), str(m.description), arr(m.capabilities), str(m.paramsLabel), num(m.contextTokens), num(m.maxOutputTokens),
    arr(m.inputModalities), arr(m.outputModalities), bool(m.isFree), bool(m.isOpenSource), bool(m.isFeatured), bool(m.isThinking), String(m.defaultTemperature), String(m.defaultMaxTokens), str(m.license),
    arr(m.deployment), m.releasedAt ? `date ${str(m.releasedAt)}` : "null", m.sourceUpdatedAt ? `date ${str(m.sourceUpdatedAt)}` : "null", String(m.sortOrder),
  ].join(", ")})`;
}

const cols = [
  "slug", "name", "provider_key", "provider_name", "source", "source_url", "api_model_id", "model_type", "badge", "description", "capabilities",
  "params_label", "context_tokens", "max_output_tokens", "input_modalities", "output_modalities", "is_free", "is_open_source", "is_featured", "is_thinking", "default_temperature", "default_max_tokens",
  "license", "deployment", "released_at", "source_updated_at", "sort_order",
];
const update = cols.filter((c) => c !== "slug").map((c) => `${c} = excluded.${c}`).join(",\n  ");

const sql = `-- Generated by \`pnpm models:sql\` from backend/src/server/ai/model-catalog.ts. Do not edit by hand.
insert into public.ai_models (${cols.join(", ")}) values
${MODEL_CATALOG.map(row).join(",\n")}
on conflict (slug) do update set
  ${update};
`;

writeFileSync(OUT, sql);
console.log(`Wrote ${MODEL_CATALOG.length} models to ${OUT}`);
